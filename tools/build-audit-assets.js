/* Reproducible shared assets. Run after changing shared styles, specifications or dictionaries. */
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const check=process.argv.includes('--check');
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const write=(f,s)=>{if(check){if(!fs.existsSync(path.join(root,f))||read(f).replace(/\r\n/g,'\n')!==s.replace(/\r\n/g,'\n'))throw Error('Generated asset out of date: '+f);return;}fs.mkdirSync(path.dirname(path.join(root,f)),{recursive:true});fs.writeFileSync(path.join(root,f),s);};
const specifications=JSON.parse(read('assets/data/activity-specs.json'));
for(const item of Object.values(specifications).filter(s=>s.ficha)){
 let html=read(item.ficha);
 const map={'Duración':'duracion','Edad recomendada':'edad','Nivel físico':'fisico','Nivel técnico':'tecnico','Mejor época':'temporada','Zona habitual':'zona'};
 html=html.replace(/(class="activity-meta-list"[\s\S]*?)(<div class="activity-detail-grid")/,(_,meta,end)=>meta.replace(/(<div><span>(.*?)<\/span><strong>)(.*?)(<\/strong><\/div>)/g,(full,start,label,old,close)=>map[label]&&item[map[label]]?start+item[map[label]]+close:full)+end);
 write(item.ficha,html);
}
const styles=['editorial-interface','i18n','language-regions','global-search','ecosystem-pathways','skeleton'];
write('assets/css/shared.css','/* Generated by tools/build-audit-assets.js; edit individual source sheets. */\n'+styles.map(f=>'/* '+f+' */\n'+read('assets/css/'+f+'.css')).join('\n'));
write('assets/js/activity-specs.js','/* Generated from assets/data/activity-specs.json by tools/build-audit-assets.js. */\nwindow.noextActivitySpecs = '+JSON.stringify(JSON.parse(read('assets/data/activity-specs.json')))+';\n');
// Keep every structured key. Split only the text catalogue, accounting for scripts and data
// rendered after load. The runtime can recover the full source catalogue if a new key is missed.
const normalize=s=>s.replace(/\s+/g,' ').trim();
const hash=s=>{let n=2166136261;for(let i=0;i<s.length;i++)n=Math.imul(n^s.charCodeAt(i),16777619);return n>>>0;};
const dynamic=[...fs.readdirSync(path.join(root,'assets/js')).filter(f=>f.endsWith('.js')).map(f=>read('assets/js/'+f)),...fs.readdirSync(path.join(root,'assets/data')).filter(f=>f.endsWith('.json')||f.endsWith('.js')).map(f=>read('assets/data/'+f))].join('\n');
const commonSource=normalize(dynamic.replace(/\\u([a-fA-F0-9]{4})/g,(_,code)=>String.fromCharCode(parseInt(code,16)))+'\nAbrir buscador (Ctrl + K)\nAbrir buscador (⌘ K)\nArtículos destacados');
const pages=fs.readdirSync(root).filter(f=>f.endsWith('.html')&&!/http-equiv="refresh"/.test(read(f)));
const langs=['es','en','fr','de','it','pt','nl'];
let total=0;
for(const lang of langs){
 const dict=JSON.parse(read('i18n/'+lang+'.json'));
 const commonKeys=new Set(Object.keys(dict.strings).filter(key=>commonSource.includes(key)));
 const common={...dict,sourceHashes:Object.keys(dict.strings).map(hash),strings:Object.fromEntries(Object.entries(dict.strings).filter(([key])=>commonKeys.has(key)))};
 write('i18n/compact/'+lang+'/common.json',JSON.stringify(common));
 for(const page of pages){
   const source=normalize(read(page)).replace(/&amp;/g,'&').replace(/&#39;/g,"'").replace(/&quot;/g,'"');
   const strings=Object.fromEntries(Object.entries(dict.strings).filter(([key])=>!commonKeys.has(key)&&source.includes(key)));
   write('i18n/compact/'+lang+'/'+page.replace('.html','.json'),JSON.stringify({strings}));
 }
 total+=Buffer.byteLength(JSON.stringify(common));
}
console.log(JSON.stringify({sharedStyles:styles.length,pages:pages.length,languages:langs.length,averageCommonBytes:Math.round(total/langs.length)}));
