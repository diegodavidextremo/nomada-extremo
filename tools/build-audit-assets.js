/* Reproducible shared assets. Run after changing shared styles, specifications or dictionaries. */
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const check=process.argv.includes('--check');
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const write=(f,s)=>{if(check){if(!fs.existsSync(path.join(root,f))||read(f).replace(/\r\n/g,'\n')!==s.replace(/\r\n/g,'\n'))throw Error('Generated asset out of date: '+f);return;}fs.mkdirSync(path.dirname(path.join(root,f)),{recursive:true});fs.writeFileSync(path.join(root,f),s);};
const specifications=JSON.parse(read('assets/data/activity-specs.json'));
const escapeHtml=value=>value.replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;');
const generatedSheets=new Set();
for(const item of Object.values(specifications).filter(s=>s.ficha)){
 if(generatedSheets.has(item.ficha))continue;
 generatedSheets.add(item.ficha);
 let html=read(item.ficha);
 const map={'Duración':'duracion','Edad recomendada':'edad','Nivel físico':'fisico','Nivel técnico':'tecnico','Mejor época':'temporada','Zona habitual':'zona','Experiencia previa':'experiencia'};
 html=html.replace(/(class="activity-meta-list"[\s\S]*?)(<div class="activity-detail-grid")/,(_,meta,end)=>{
   if(!meta.includes('<span>Experiencia previa</span>')){
     meta=meta.replace(/<\/div>(\s*)$/, '<div><span>Experiencia previa</span><strong></strong></div></div>$1');
   }
   return meta.replace(/(<div><span>(.*?)<\/span><strong>)(.*?)(<\/strong><\/div>)/g,
     (full,start,label,old,close)=>map[label]&&item[map[label]]?start+escapeHtml(item[map[label]])+close:full)+end;
 });
 write(item.ficha,html);
}
const normalizeActivity=value=>value.normalize('NFD').replace(/\p{M}/gu,'');
const catalogSpecs=new Map(Object.entries(specifications).map(([name,item])=>[normalizeActivity(name),item]));
const catalog=read('actividades.html').replace(
 /(<div class="(?:ficha reveal|catalog-mode)"[^>]*data-activity-source="([^"]+)"[^>]*>[\s\S]*?)(?=<div class="(?:ficha reveal|catalog-mode)"|<\/section>)/g,
 (full,card,name)=>{
   const item=catalogSpecs.get(normalizeActivity(name));
   if(!item)throw Error('Missing activity specification: '+name);
   // Grouped cards describe each modality separately. Their badge is a filter category.
   if(!card.includes('class="ficha-meta"'))return full;
   const updated=card.replace(/<div class="ficha-meta">[\s\S]*?<\/div>(?:<p class="catalog-requirements">[\s\S]*?<\/p>)?/,meta=>{
     const tags=[...meta.matchAll(/<span class="ficha-tag">([^<]*)<\/span>/g)].slice(meta.includes('data-spec-duration')?0:1)
       .map(match=>match[1]).filter(tag=>!/^(?:Desde \d|Edad según|Todo el año|Oct–Mayo)/i.test(tag));
     const facts=[item.duracion,item.tecnico].map((value,index)=>'<span class="ficha-tag" '+(index?'data-spec-level':'data-spec-duration')+'>'+escapeHtml(value)+'</span>');
     return '<div class="ficha-meta">'+facts.join('')+tags.map(tag=>'<span class="ficha-tag">'+tag+'</span>').join('')+'</div>'+
       '<p class="catalog-requirements"><strong>Edad recomendada</strong> · '+escapeHtml(item.edad)+'<br><strong>Experiencia previa</strong> · '+escapeHtml(item.experiencia)+'</p>';
   });
   // Preserve the short categories used by the controls while showing the technical level in the facts.
   return updated.replace(/(<div class="ficha reveal"[^>]*>)([\s\S]*?)<span class="nivel-badge[^"]*">([^<]+)<\/span>/,
     (match,opening,photo,badge)=> (opening.includes('data-levels=') ? opening :
       opening.replace(/>$/, ' data-levels="'+escapeHtml(badge)+'">'))+photo);
 }).replace(/<article class="process-card editorial-top-card">[\s\S]*?<\/article>/g,card=>{
   if(!card.includes('class="editorial-top-facts"'))return card;
   const file=card.match(/href="([^"]+\.html)"/)?.[1];
   const item=Object.values(specifications).find(spec=>spec.ficha===file);
   if(!item)throw Error('Missing featured activity specification: '+file);
   return card.replace(/<div class="editorial-top-facts">[\s\S]*?<\/div>/,
     '<div class="editorial-top-facts"><span>'+escapeHtml(item.tecnico)+'</span><span>'+escapeHtml(item.duracion)+'</span></div>');
 });
write('actividades.html',catalog);
const styles=['editorial-interface','i18n','language-regions','global-search','ecosystem-pathways','skeleton'];
write('assets/css/shared.css','/* Generated by tools/build-audit-assets.js; edit individual source sheets. */\n'+styles.map(f=>'/* '+f+' */\n'+read('assets/css/'+f+'.css')).join('\n'));
write('assets/js/activity-specs.js','/* Generated from assets/data/activity-specs.json by tools/build-audit-assets.js. */\nwindow.noextActivitySpecs = '+JSON.stringify(JSON.parse(read('assets/data/activity-specs.json')))+';\n');
// Keep every structured key. Split only the text catalogue, accounting for scripts and data
// rendered after load. The runtime can recover the full source catalogue if a new key is missed.
const normalize=s=>s.replace(/\s+/g,' ').trim();
const hash=s=>{let n=2166136261;for(let i=0;i<s.length;i++)n=Math.imul(n^s.charCodeAt(i),16777619);return n>>>0;};
const dynamic=[...fs.readdirSync(path.join(root,'assets/js')).filter(f=>f.endsWith('.js')).map(f=>read('assets/js/'+f)),...fs.readdirSync(path.join(root,'assets/data')).filter(f=>f.endsWith('.json')||f.endsWith('.js')).map(f=>read('assets/data/'+f))].join('\n');
const commonSource=normalize(dynamic.replace(/\\u([a-fA-F0-9]{4})/g,(_,code)=>String.fromCharCode(parseInt(code,16)))+'\nAbrir buscador (Ctrl + K)\nAbrir buscador (⌘ K)\nArtículos destacados');
const pages=fs.readdirSync(root).filter(f=>f.endsWith('.html')&&!/http-equiv="refresh"/.test(read(f)));
const langs=['es','en','fr','de','it','pt','nl'];
let total=0;
for(const lang of langs){
 const dict=JSON.parse(read('i18n/'+lang+'.json'));
 // Spanish prose is already in the HTML. Keep explicit bindings and only store actual text overrides.
 const strings=Object.entries(dict.strings).filter(([key,value])=>lang!=='es'||key!==value);
 const commonKeys=new Set(strings.filter(([key])=>commonSource.includes(key)).map(([key])=>key));
 const common={...dict,sourceHashes:strings.map(([key])=>hash(key)),strings:Object.fromEntries(strings.filter(([key])=>commonKeys.has(key)))};
 write('i18n/compact/'+lang+'/common.json',JSON.stringify(common));
 for(const page of pages){
   const source=normalize(read(page)).replace(/&amp;/g,'&').replace(/&#39;/g,"'").replace(/&quot;/g,'"');
   const pageStrings=Object.fromEntries(strings.filter(([key])=>!commonKeys.has(key)&&source.includes(key)));
   write('i18n/compact/'+lang+'/'+page.replace('.html','.json'),JSON.stringify({strings:pageStrings}));
 }
 total+=Buffer.byteLength(JSON.stringify(common));
}
console.log(JSON.stringify({sharedStyles:styles.length,pages:pages.length,languages:langs.length,averageCommonBytes:Math.round(total/langs.length)}));
